// Idempotency-related MySQL error numbers: re-running DDL that already
// applied (table/column/constraint already exists) is expected and safe to
// ignore, since the generated migration is re-applied on every boot.
const IGNORABLE_DDL_ERRNOS = new Set([
  1050, // ER_TABLE_EXISTS_ERROR
  1060, // ER_DUP_FIELDNAME
  1061, // ER_DUP_KEYNAME
  1826, // ER_FK_DUP_NAME / duplicate foreign key constraint
  1022, // ER_DUP_KEY
]);

/**
 * The table DDL itself is generated by drizzle-kit from src/db/schema.ts
 * (`bun run db:generate`, committed under drizzle/) rather than hand-written
 * here, so the two never drift: this just applies whatever drizzle-kit last
 * emitted, statement by statement, tolerating "already exists" errors so it
 * is safe to run on every boot against an already-migrated database.
 */
async function applyGeneratedMigrations(client: Pool): Promise<void> {
  const migrationsDir = path.resolve(process.cwd(), "drizzle");
  if (!fs.existsSync(migrationsDir)) {
    console.warn("[NiniMed DB] No drizzle/ migrations folder found; skipping schema apply.");
    return;
  }
  const files = fs
    .readdirSync(migrationsDir)
    .filter((f) => f.endsWith(".sql"))
    .sort();

  for (const file of files) {
    const sql = fs.readFileSync(path.join(migrationsDir, file), "utf8");
    const statements = sql
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean);

    for (const statement of statements) {
      try {
        await client.query(statement);
      } catch (err: any) {
        if (!IGNORABLE_DDL_ERRNOS.has(err?.errno)) {
          console.error(`[NiniMed DB] Migration statement failed (${file}):`, err?.message || err);
          if (process.env.NINIMED_STRICT_DB === "true") throw err;
        }
      }
    }
  }
}

export async function ensureDatabaseInitialized(
  client: Pool,
  options: DatabaseInitializationOptions = {},
) {
  const shouldSeed = options.seed ?? true;
  try {
    console.log("⚡ Checking and synchronizing NiniMed MySQL schema...");

    // 1. Authentication tables/columns first. Login must not depend on the
    //    full schema apply below having run to completion. On a fresh
    //    database `users` does not exist yet; the pass is repeated after.
    const syncAuthSchema = async () => {
      try {
        await ensureAuthSchemaWithClient(client);
      } catch (authErr) {
        console.error("Auth schema synchronization failed:", authErr);
        if (process.env.NINIMED_STRICT_DB === "true") throw authErr;
      }
    };
    await syncAuthSchema();

    // 2. Apply the full generated schema (all tables, indexes, foreign keys).
    await applyGeneratedMigrations(client);

    console.log("✅ MySQL schema verification complete (all tables, pricing, pharmacy and lab protocols confirmed).");

    // 3. Auth schema again, now that `users` is guaranteed to exist.
    await syncAuthSchema();

    if (!shouldSeed) {
      console.log("ℹ️ Seed data disabled for this database operation.");
      return;
    }

    // 4. Check if seed data exists before inserting.
    const [[orgCheck]] = await client.query<any[]>(`SELECT COUNT(*) as count FROM organizations`);

    if (orgCheck && Number(orgCheck.count) > 0) {
      console.log("ℹ️ Database already has seed organizations. Skipping initial seed insert.");
      await syncComprehensiveCatalogues(client);
      await seedDemoAccounts(client);
      return;
    }

    console.log("🌱 Inserting initial seed data for NiniMed Health System...");
    await seedInitialData(client);
    await syncComprehensiveCatalogues(client);
    await seedDemoAccounts(client);
  } catch (error: any) {
    if (error?.code === "ECONNREFUSED" || error?.message?.includes("ECONNREFUSED")) {
      console.log("ℹ️ Database connection not ready yet. Schema synchronization will occur upon container connection.");
    } else {
      console.error("Database initialization note:", error?.message || error);
      if (process.env.NINIMED_STRICT_DB === "true") {
        throw error;
      }
    }
  }
}

