export async function syncComprehensiveCatalogues(client: Pool) {
  try {
    console.log("⚡ Synchronizing Intensive Laboratory Protocols...");
    for (const lab of LABORATORY_PROTOCOLS_CATALOGUE) {
      const serviceCode = `LAB_${lab.testCode.replace(/[\/\s-]/g, "_")}`;
      const desc = `Specimen: ${lab.specimen} (${lab.tubeContainer}). Ref: ${lab.referenceRangeAdult}${lab.criticalValues ? " | Critical: " + lab.criticalValues : ""}`;
      const fullName = `${lab.testName} (${lab.testCode})`;
      const metadataJson = JSON.stringify({
        testCode: lab.testCode,
        testName: lab.testName,
        specimen: lab.specimen,
        tubeContainer: lab.tubeContainer,
        collectionProtocol: lab.collectionProtocol,
        handlingStorage: lab.handlingStorage,
        referenceRangeAdult: lab.referenceRangeAdult,
        criticalValues: lab.criticalValues,
        turnaroundTime: lab.turnaroundTime,
        methodology: lab.methodology,
        category: lab.category,
        priceEtb: lab.priceEtb,
        isStatAvailable: lab.isStatAvailable || false,
      });
      const itemsJson = JSON.stringify([
        `Specimen: ${lab.specimen}`,
        `Container: ${lab.tubeContainer}`,
        `Collection: ${lab.collectionProtocol}`,
        `Storage: ${lab.handlingStorage}`,
        `Turnaround: ${lab.turnaroundTime}`,
        `Methodology: ${lab.methodology}`,
        lab.criticalValues ? `Critical Alert: ${lab.criticalValues}` : "No critical limits specified",
      ]);

      await client.query(
        `INSERT INTO service_pricing_catalog (
            id, service_code, category, name, description, base_price, currency, is_free, is_active, updated_at
        ) VALUES (
            UUID(), ?, 'laboratory', ?, ?, ?, 'ETB', FALSE, TRUE, NOW()
        )
        ON DUPLICATE KEY UPDATE
            name = VALUES(name),
            description = VALUES(description),
            base_price = VALUES(base_price),
            is_active = TRUE`,
        [serviceCode, fullName, desc, lab.priceEtb]
      );

      await client.query(
        `INSERT INTO clinical_catalog_protocols (
            id, tenant_id, kind, department_id, name, indication, items, metadata, is_active, created_at, updated_at
        ) VALUES (
            UUID(), '00000000-0000-0000-0000-000000000001', 'protocol', 'laboratory', ?, ?, ?, ?, TRUE, NOW(), NOW()
        )
        ON DUPLICATE KEY UPDATE
            indication = VALUES(indication),
            items = VALUES(items),
            metadata = VALUES(metadata),
            is_active = TRUE`,
        [fullName, "Diagnostic protocol for " + lab.testName + " (" + lab.category + "). Specimen: " + lab.specimen, itemsJson, metadataJson]
      );
    }

    console.log("⚡ Synchronizing Master Pharmacy Catalogue Items...");
    for (const item of PHARMACY_MASTER_CATALOGUE) {
      const barcode = "628" + item.drugCode.replace(/[^0-9]/g, "").padStart(9, "0");
      const unitCost = Number((item.priceEtb * 0.65).toFixed(2));
      const sellingPrice = Number(item.priceEtb.toFixed(2));
      const maxStock = item.reorderLevel * 4;

      await client.query(
        `INSERT INTO drug_catalog (
            id, tenant_id, generic_name, brand_name, strength, dosage_form, route,
            atc_code, barcode, package_size, reorder_level, max_stock,
            default_unit_cost, default_selling_price, storage_condition,
            item_code, category, section_number, section_name, is_controlled, rx_otc, is_active, created_at, updated_at
        ) VALUES (
            UUID(), '00000000-0000-0000-0000-000000000001', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, TRUE, NOW(), NOW()
        )
        ON DUPLICATE KEY UPDATE
            generic_name = VALUES(generic_name),
            brand_name = VALUES(brand_name),
            strength = VALUES(strength),
            dosage_form = VALUES(dosage_form),
            route = VALUES(route),
            category = VALUES(category),
            section_number = VALUES(section_number),
            section_name = VALUES(section_name),
            is_controlled = VALUES(is_controlled),
            rx_otc = VALUES(rx_otc),
            default_selling_price = VALUES(default_selling_price),
            reorder_level = VALUES(reorder_level),
            is_active = TRUE`,
        [
          item.genericName,
          item.brandName,
          item.strength,
          item.form,
          item.route,
          item.atcCode || item.drugCode,
          barcode,
          item.reorderUnit || "unit",
          item.reorderLevel,
          maxStock,
          unitCost,
          sellingPrice,
          item.storageCondition || "ambient",
          item.drugCode,
          item.category,
          item.sectionNumber,
          item.sectionName,
          item.isControlled,
          item.rxOtc,
        ]
      );
    }

    console.log("✅ Synchronized pharmacy and laboratory catalogues.");
  } catch (err: any) {
    console.warn("Catalog synchronization notice:", err?.message || err);
  }
}
